import { z } from "zod";

/*
 * Модуль → unix-сокет агента. Один объект на все исходы фазы.
 * Агент публикует его как есть, дописав только `v` и `kind`.
 *
 * Это единственный источник данных о самом запросе. Записи инспекторов
 * (`kind=inspector`) рассказывают лишь про себя: что сработало у них внутри.
 * Ни адреса, ни маршрута, ни размеров, ни того, кто промолчал, там нет и
 * взяться неоткуда. Поэтому контекст запроса собираем здесь и полностью.
 *
 * Три вопроса — три поля: что сделали (`verdict`), почему (`code`),
 * кто (`by` — ключ в `inspectors`). Остальное — контекст.
 *
 * Датаграмма ограничена 8 КБ с обеих сторон (`NGX_HTTP_WAF_AUDIT_JSON`,
 * `handoff.MaxBytes`), переполнение теряет запись целиком и молча. Поэтому
 * длинное содержимое — заголовки, тело, строка запроса — сюда не копируется:
 * едет локатор обменника, содержимое достаётся по нему.
 */

/** Итог модуля. `score` сюда не попадает: порог уже свёрнут в `deny`. */
const Final = z.enum(["allow", "redirect", "deny"]);

/** Вердикт участника. `score` — заявка в сумму, решает по ней модуль. */
const Verdict = z.enum(["allow", "score", "redirect", "deny"]);

/**
 * Почему вынесен итог. Ставит модуль, закрытый набор, одна ветка — один код.
 *
 * | код | кто решил | когда |
 * | --- | --- | --- |
 * | `local_list`   | модуль    | `waf_local_check`, action=block             |
 * | `local_rate`   | модуль    | `waf_local_rate`, action=block              |
 * | `inspector`    | инспектор | решающий ответил `deny` или `redirect`      |
 * | `score`        | модуль    | сумма дошла до `deny_at`, явного `deny` нет |
 * | `fail_timeout` | политика  | волна не уложилась в дедлайн фазы           |
 * | `fail_absent`  | политика  | на subject инспектора нет подписчиков       |
 * | `fail_bus`     | политика  | шина не приняла публикацию волны            |
 * | `fail_body`    | политика  | тело недоступно: лимит, обрыв, обменник        |
 */
const Code = z.enum([
  "local_list",
  "local_rate",
  "inspector",
  "score",
  "fail_timeout",
  "fail_absent",
  "fail_bus",
  "fail_body",
]);

/** Ключ модуля в `inspectors`. Инспектору такое имя брать нельзя. */
const SELF = "module";

/** Объект просьбы записи в `actions`: см. поля `headers` / `args` / `body`. */
const RecordObject = z
  .object({
    set: z.enum(["on", "off"]).optional(),
    limit: z.number().int().nonnegative().optional(),
    source: z.enum(["store", "original"]).optional(),
  })
  .strict();

/**
 * Указатель на объект в обменнике, не содержимое: `{store, driver, key, size}`
 * и, у тела, `sha256` / `truncated` / `encoding` / `expires_at`. Форма общая
 * с сообщением инспектору, она описана в inspector.schema.json.
 *
 * Адресации (`store`, `driver`, `key`, `expires_at`, `hint`) может не быть:
 * она есть ровно тогда, когда по ней ещё можно что-то достать. Всё, что не
 * названо в `store.archive`, модуль удалил из обменника сразу после вердикта, и
 * от такого объекта остаются только размер, контрольная сумма и признаки
 * полноты.
 *
 * У архивного локатора `expires_at` — срок из lifecycle-правила бакета, как его
 * назвало хранилище; `hint` не переезжает вовсе. Поля нет — срок неизвестен, а
 * не вышел: разница в том, идти ли за объектом.
 *
 * Недоступность — `{unavailable, size}`: к `oversize`, `store_error`,
 * `store_unconfigured`, `streaming_not_supported`, `transform_failed` агент
 * добавляет свои четыре. `expired` — ключа в обменнике уже не было, когда агент до
 * него добрался; `empty` — объект требовался и оказался пуст, поэтому в архив
 * не пошёл вовсе; `overload` — очередь архивации была переполнена и `PUT` не
 * пробовали; `archive_error` — `PUT` не удался. Backpressure отделён от отказа
 * хранилища намеренно: лечатся они разным. Локатор, указывающий в пустоту, не
 * публикуется никогда.
 *
 * `null` — класть было нечего либо обменник не задействован: локального бана
 * волна не касалась, и локаторов у него нет.
 */
const Locator = z.object({}).passthrough().nullable();

/**
 * Пара превью: имя, значение и необязательный признак урезанного значения.
 * Третий элемент есть ровно тогда, когда значение не влезло в потолок на пару и
 * поехало префиксом.
 */
const PreviewPair = z.union([
  z.tuple([z.string().min(1), z.string()]),
  z.tuple([z.string().min(1), z.string(), z.literal(1)]),
]);

/**
 * Одна форма записи на всех участников: и на модуль (ключ `module`), и на
 * инспектора. Разбирать запись, заглядывая в её ключ, не нужно.
 *
 * Ровно одно из `verdict` / `state`: участник либо ответил, либо нет.
 * Остальные поля — то, чего нет ни в одном другом сообщении: их знает
 * только модуль, потому что он и раздавал волну, и мерил время, и применял
 * веса маршрута.
 */
const Entry = z
  .object({
    /** Ответил. У записи `module` — итог фазы, он же верхний `verdict`. */
    verdict: Verdict.optional(),

    /**
     * Не ответил, поэтому вердикта нет. Без этого поля молчуна в сообщении
     * не видно вовсе, и `code: "fail_timeout"` не объясняет, из-за кого.
     *
     * `timeout`  — спрашивали, не уложился в дедлайн фазы
     * `absent`   — на его subject не было подписчиков
     * `skipped`  — не спрашивали: `sample=` или разомкнутый предохранитель
     * `off`      — не спрашивали: режим off, свой на вызове (`mode=off`) или
     *              поставленный соседом управляющим глаголом
     */
    state: z.enum(["timeout", "absent", "skipped", "off"]).optional(),

    /**
     * Что легло в `score.total` (у пассивного — в `score.shadow`): при
     * `verdict: "score"` — заявка, как её прислал инспектор; у совещательного
     * (`role: "vote"`) с `verdict: "deny"` — 100. Множителя на маршруте нет,
     * поэтому число одно и арифметика итога сходится по нему.
     */
    score: z.number().int().positive().optional(),

    /**
     * Round-trip, миллисекунды: публикация волны → разбор ответа. Мерит
     * модуль. В `kind=inspector` есть только `engine_ms` — время внутри
     * движка, без шины и очереди, поэтому «инспектор тормозит» видно
     * исключительно отсюда.
     */
    latency_ms: z.number().nonnegative().optional(),

    /**
     * Роль на этом маршруте. Поля нет — боевой, его заявка идёт в
     * `score.total`. `passive` идёт в `score.shadow` и на трафик не влияет.
     * `vote` — совещательный: очки в `score.total`, `deny` как 100, сам не
     * решает. `active` — действующая роль, когда вызов записан
     * `mode=passive` или `mode=vote`, а сосед перевёл глаголом `active`.
     */
    role: z.enum(["passive", "vote", "active"]).optional(),

    /**
     * Профиль маршрута, с которым инспектора звали, — непрозрачная для
     * модуля строка. Поля нет — `default`. Один и тот же инспектор на
     * разных location работает по-разному, и без профиля его вердикт
     * не воспроизвести.
     */
    profile: z.string().min(1).optional(),
  })
  .strict()
  .refine((e) => (e.verdict === undefined) !== (e.state === undefined), {
    message: "ровно одно из verdict / state: участник либо ответил, либо нет",
  })
  .refine(
    (e) =>
      e.verdict === "score"
        ? e.score !== undefined
        : e.score === undefined || (e.verdict === "deny" && e.role === "vote"),
    {
      message:
        "score — что легло в сумму: есть при verdict score и у совещательного deny, больше нигде",
    },
  );

export const AgentMessage = z
  .object({
    /* --- идентификация ---------------------------------------------------- */

    /** UUID v4 запроса. Сквозной ключ: тот же в волне и в `kind=inspector`. */
    ray: z
      .string()
      .regex(
        /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/,
      ),
    /** `waf_node_id`. */
    node: z.string().min(1),
    /** В какой фазе вынесен итог. */
    phase: z.enum(["request", "response", "frame"]),

    /**
     * Момент поступления запроса, UTC с миллисекундами. Ставит модуль, а не
     * агент: агентское время — это момент публикации, то есть после сокета,
     * очереди и планировщика. Для порядка событий и для склейки с access-логом
     * нужно начало обработки. Вместе с `waf_latency_us` даёт и то и другое.
     */
    ts: z.string().datetime({ offset: false }),

    /* --- соединение ------------------------------------------------------- */

    /** `$remote_addr` после realip — то же, что уехало инспекторам. */
    client_ip: z.string().min(1),
    client_port: z.number().int().nonnegative(),

    /**
     * Адрес, на котором приняли соединение. На wildcard-listen и на нескольких
     * адресах иначе не понять, какой именно фронт поймал трафик.
     */
    server_ip: z.string().min(1),
    server_port: z.number().int().nonnegative(),

    /** Только на HTTPS. Отпечаток рукопожатия добавим, когда будет источник. */
    tls: z
      .object({
        version: z.string().min(1),
        /** Может расходиться с `http.host` — это само по себе сигнал. */
        sni: z.string().min(1).optional(),
      })
      .strict()
      .optional(),

    /* --- запрос ----------------------------------------------------------- */

    http: z
      .object({
        method: z.string().min(1),
        scheme: z.enum(["http", "https"]),
        /** Заголовок Host. */
        host: z.string(),
        /** Путь без строки запроса. */
        uri: z.string().min(1),
        /** `HTTP/1.1`, `HTTP/2.0`: поверхность атаки у версий разная. */
        version: z.string().min(1),

        /**
         * Длина строки запроса в байтах. Содержимое сюда не кладём — оно
         * уходит в обменник, см. `store.args`. Ноль означает, что query не было:
         * это видно даже когда запись строки выключена.
         */
        args_size: z.number().int().nonnegative(),
        /** Размер сырых заголовков и их число: и то и другое — признак сканера. */
        headers_size: z.number().int().nonnegative(),
        headers_count: z.number().int().nonnegative(),
        /**
         * Сколько байт тела модуль прочитал. С Content-Length расходится при
         * chunked и при усечении — усечение отмечено в локаторе `store.body`.
         */
        body_size: z.number().int().nonnegative(),
        /** Content-Type без параметров. Нет заголовка — нет поля. */
        content_type: z.string().min(1).optional(),

        /**
         * Код, который модуль отдал клиенту, не апстрим. На `allow` фазы
         * запроса апстрим ещё не отвечал, поле 0.
         */
        status: z.number().int().nonnegative(),

        /**
         * Код самого приложения, до вмешательства. Нет поля — апстрим не
         * отвечал: у фазы запроса так всегда.
         *
         * Отдельно от `status` потому, что это разные факты. В `status` один и
         * тот же 418 означает и «приложение ответило успехом, а мы закрыли
         * ответ», и «мы закрыли запрос, приложение не отвечало вовсе», — а это
         * первый вопрос при разборе инцидента фазы ответа.
         */
        upstream_status: z.number().int().positive().optional(),
      })
      .strict(),

    /**
     * Какая конфигурация сработала. Без этого вопрос «почему на этот URL
     * правило не применилось» не разбирается: набор инспекторов, пороги и веса
     * заданы на location.
     */
    route: z
      .object({
        server_name: z.string().min(1),
        location: z.string().min(1),
        /**
         * Uuid пути в панели -- `waf_route_id` блока location. Это ключ, по
         * которому журнал схлопывает трафик маршрута: у regex-пути URI
         * разные, а маршрут один, и имя блока для этого не годится -- его
         * переписывают, а история должна остаться той же. Поля нет у
         * модуля без директивы: конфигурация собрана не контроллером.
         */
        id: z.string().min(1).optional(),
      })
      .strict(),

    /* --- решение ---------------------------------------------------------- */

    verdict: Final,
    /** Нет ровно на `allow`. */
    code: Code.optional(),
    /** Чей вердикт стал итогом: `module` либо имя решающего инспектора. */
    by: z.string().min(1),

    /**
     * Есть, если маршрут считает счёт, то есть порог задан на location. Не
     * «если набралось»: ноль при известном пороге значит «считали, никто не
     * начислил», а отсутствие секции — «на этом маршруте не считают», и
     * путать это нельзя. При `code: "score"` обязателен.
     */
    score: z
      .object({
        /** Сумма `score` обязательных и совещательных. Ноль — законное значение. */
        total: z.number().int().nonnegative(),
        /** Порог маршрута. Задан на location, без него события несопоставимы. */
        deny_at: z.number().int().positive(),
        /**
         * Вклад пассивных. В `total` не входит и порог не двигает: это ответ
         * на «сколько было бы, переведи их в боевые». Совещательные сюда не
         * попадают: их очки уже в `total`.
         */
        shadow: z.number().int().positive().optional(),
      })
      .strict()
      .optional(),

    /**
     * Все участники фазы: `module` есть всегда, инспектор — если его звали.
     * Промолчавший тоже здесь, со `state` вместо вердикта.
     */
    inspectors: z.record(z.string().min(1), Entry),

    /**
     * Живые действия запроса — просьбы инспекторов друг к другу, которые
     * модуль перенёс, но не исполнял. Секции нет, если никто ни о чём не
     * просил либо канал выключен (`waf_actions_max 0`).
     *
     * Здесь перечислены **все** живые, а не только применённые: применённые
     * называет получатель, в своём `kind=inspector`. Без этой пары вопрос
     * «почему клиент увидел капчу» разбирается только по логам инспекторов.
     *
     * Форма и словари — [inspector-actions.md](../inspector-actions.md).
     */
    actions: z
      .array(
        z
          .object({
            /** Кто попросил. Имя из реестра. */
            from: z.string().min(1).nullable(),
            /**
             * Кому адресовано. Поля нет у широковещательного: «всем» — это не
             * имя адресата, и печатать его звёздочкой значило бы завести в
             * схеме имя, которого нет в реестре.
             */
            to: z.string().min(1).optional(),
            /**
             * Фаза вызова адресата у управляющих глаголов: на проводе
             * инспектора это `phase`, здесь `phase` уже значит «где
             * высказано», поэтому адрес печатается рядом с `to`. Поля нет
             * у просьбы без фазы -- режим получили все вызовы имени.
             */
            to_phase: z.enum(["request", "response", "frame"]).optional(),
            do: z.enum(["challenge", "threshold", "skip", "reauth", "note", "mutate", "active", "passive", "vote", "off", "audit", "archive", "mark", "score"]),
            /**
             * Ось: о ком высказывание, а не какой рычаг у получателя дёрнуть.
             * Превращает её в ключ получатель — только он знает свою нарезку
             * на подсети и свою cookie сессии.
             */
            apply: z.enum(["request", "response", "ip", "asn", "session", "conn"]),
            /** Машинный повод. Модуль его не толкует. */
            code: z
              .string()
              .regex(/^[A-Z][A-Z0-9_]*$/)
              .max(64)
              .optional(),
            /** Только при `do: "threshold"`. Плюс поднимает порог, то есть смягчает. */
            delta: z.number().int().min(-1000).max(1000).optional(),
            /** Только при `do: "note"`. Предложенный вес, получатель режет своим потолком. */
            value: z.number().int().min(-1000).max(1000).optional(),
            /**
             * Только при `do: "note"`: имя корзины получателя — селектор
             * поверх его правил приёма. Пусто — корзину называет правило.
             */
            counter: z
              .string()
              .regex(/^[A-Za-z0-9][A-Za-z0-9._-]*$/)
              .max(64)
              .optional(),
            /**
             * Только при `do: "mark"`: метка события. Произвольная строка
             * оператора; модуль её не толкует, а складывает со всеми
             * маркерами запроса в множество `markers` этой записи.
             */
            marker: z.string().min(1).max(128).optional(),
            /** Только при `do: "mutate"`: какую группу модификаторов получателя переключить и куда. */
            group: z
              .string()
              .regex(/^[A-Za-z0-9][A-Za-z0-9._-]*$/)
              .max(64)
              .optional(),
            /**
             * У `mutate` -- куда переключить группу; у `audit` / `archive` --
             * писать ли запрос в журнал / оставлять ли объекты агенту. Эти
             * два исполняет модуль от любого инспектора, спрошенного на
             * маршруте: их исход -- сама эта запись и её `store.archive`.
             */
            set: z.enum(["on", "off"]).optional(),
            /** Только при `do: "archive"` с `set: "on"`: срок в архиве секундами, ноль -- вечно. */
            ttl: z.number().int().nonnegative().optional(),
            /**
             * Объекты просьбы записи (`audit` / `archive` с `set: "on"`), каждый
             * со своей стороной (`off` исключает), размером (`archive` -- сколько
             * байт уедет, `audit` -- бюджет превью) и источником (как снято либо
             * оригинал без масок снимка).
             */
            headers: RecordObject.optional(),
            args: RecordObject.optional(),
            body: RecordObject.optional(),
            /** На какой фазе высказано. */
            phase: z.enum(["request", "response", "frame"]),
            /**
             * Отправитель был пассивен — значит, действие **никому не
             * доставлено**: записи пассивного в `prior` нет вовсе. Здесь оно
             * перечислено всё равно, и это единственное место, где «что было
             * бы, если инспектора включить» вообще можно прочитать.
             */
            passive: z.boolean(),
          })
          .strict(),
      )
      .optional(),

    /**
     * Маркеры записи: метки, которые попросили поставить инспекторы глаголом
     * `mark` ([inspector-actions.md](../inspector-actions.md#маркеры)).
     * Множество строк, а не пары «метка — кто поставил»: одна и та же метка от
     * двух инспекторов — один маркер, а кто и по какому поводу просил, видно в
     * `actions` этой же записи.
     *
     * Секции нет, если никто ничего не пометил. Строки — как их написал
     * оператор в профиле отправителя: модуль их не толкует и не нормализует.
     */
    markers: z.array(z.string().min(1).max(128)).optional(),

    /**
     * Чьи сессии назвали инспекторы: секции `sessions` их реплаев
     * ([verdict-protocol.md](../verdict-protocol.md#секция-sessions)). Модуль
     * ничего из этого не применяет — только переносит, дописав отправителя.
     * Секции нет, если никто ничего не назвал; у кадров WebSocket её нет
     * никогда — они читают сессии из записи рукопожатия под тем же `ray`.
     */
    sessions: z
      .array(
        z
          .object({
            /** Кто назвал. Имя из реестра. */
            by: z.string().min(1).nullable(),
            /** Имя источника у отправителя: у калитки — источник входа. */
            source: z.string().min(1).max(64),
            /** `own` — выписал контур, `jwt` — чужой токен, `app` — кука приложения. */
            kind: z.string().min(1).max(16),
            /** Логин. Пусто — сессия есть, а кто это, отправитель не знает. */
            user: z.string().max(256),
            /**
             * Идентификатор сессии, не сама кука: у своей сессии — `sid`, у
             * чужой — хеш. Сырой секрет сюда не кладут.
             */
            id: z.string().max(128),
            /** Подпись сошлась. `false` у разбора без ключа: claims написал клиент. */
            verified: z.boolean(),
            /** Unix-секунды выдачи и срока. Поля нет — отправитель не прислал. */
            issued: z.number().int().nonnegative().optional(),
            expires: z.number().int().nonnegative().optional(),
            /** Группы одной строкой через запятую. */
            groups: z.string().max(256).optional(),
            /**
             * Отправитель пассивен: заголовки личности приложению не легли, а
             * запись здесь — единственное место, где видно, кого назвала бы
             * калитка, будь она боевой. Поля нет у боевого.
             */
            passive: z.literal(true).optional(),
          })
          .strict(),
      )
      .optional(),

    /* --- контекст --------------------------------------------------------- */

    /**
     * Стандартный набор модуля (user_agent, referer, xff, accept_language,
     * origin, content_type, accept, request_id) плюс объявленные `waf_var` --
     * в записи всегда целиком, независимо от `vars=` объявлений инспекторов.
     * Непустые, значение режется до 256 байт. Сюда же попадает всё, чего у
     * модуля своего нет: страна и ASN из geoip-модуля, свои переменные
     * конфигурации.
     */
    vars: z.record(z.string().min(1), z.string().min(1)).optional(),

    /**
     * Локаторы обменника: где лежит то, что в датаграмму не влезает. Достаётся
     * по ключу, когда запись аудита разворачивают.
     *
     * Секции нет, если обменник не задействован — локальный бан волны не
     * открывал. Отдельное поле — `null`, если этот объект не сохраняли:
     * запись выключена директивой либо сохранять было нечего.
     *
     * Разобранных cookie нет: сырой `Cookie` лежит внутри `headers`.
     */
    store: z
      .object({
        headers: Locator,
        /** Строка запроса. Живёт в обменнике по тем же правилам, что тело. */
        args: Locator,
        body: Locator,

        /**
         * Что модуль оставил жить: «вид объекта → условия записи». Владение
         * этими ключами перешло агенту — он перекладывает их в архив, подменяет
         * локаторы выше архивными и вычищает обменник сам. Поля нет — агент к
         * обменнику не прикасается, модуль всё удалил.
         *
         * `ttl` — срок хранения в секундах, его называет маршрут
         * (`waf_archive request ... ttl=`). Агент уносит его тегом объекта, а
         * удаляет по этому тегу lifecycle-правило бакета. Ноль — хранить вечно:
         * тега тогда нет вовсе и правилу не с чем совпасть.
         *
         * `limit` — сколько байт объекта записать. Режет агент, а не модуль: в
         * обменнике объект лежит целиком, потому что его мог попросить инспектор.
         * Урезанный объект едет с `truncated` в архивном локаторе. Поля нет —
         * пишется весь объект.
         *
         * Условия у каждого вида свои: строка директивы настраивает только
         * названные в ней объекты, и назначить телу свой предел, не переписывая
         * заголовки, иначе было бы нечем.
         *
         * Поле — сиблинг локаторов, а не поле внутри локатора: форма локатора
         * общая с inspector.schema.json, а инспектору этот признак не нужен.
         *
         * В опубликованной записи условия сами по себе ничего не открывают —
         * локаторы к этому моменту уже архивные. Они остаются, чтобы по записи
         * было видно, когда объекта не станет и весь ли он там.
         *
         * `allow` / `mask` / `deny` — списки имён из строки `waf_archive`
         * этого объекта: агент фильтрует ими сверх вида, который лежит в
         * обменнике. Полей нет — списков у объекта не задано.
         *
         * Набор, срок и предел здесь — уже с учётом глагола `archive` канала
         * действий: сосед мог оставить объекты вопреки `when=` или назвать
         * свой срок; кто и о чём просил,
         * видно в `actions` той же записи.
         */
        archive: z
          .record(
            z.enum(["headers", "args", "body"]),
            z
              .object({
                ttl: z.number().int().nonnegative(),
                limit: z.number().int().positive().optional(),
                allow: z.array(z.string().min(1)).optional(),
                mask: z.array(z.string().min(1)).optional(),
                deny: z.array(z.string().min(1)).optional(),
              })
              .strict(),
          )
          .optional(),
      })
      .strict()
      .optional(),

    /* --- превью ------------------------------------------------------------
     *
     * Срез запроса, который едет в самой записи и живёт в ней. Не замена
     * обменнику: там адрес объекта, который достают по одной записи за раз,
     * здесь — фиксированный по объёму кусок, по которому ищут поперёк всех
     * записей сразу («у кого был этот заголовок», «где в теле встречалось
     * это слово»).
     *
     * Объём задаёт конфигурация маршрута (`waf_preview`), а не запрос: сумма
     * бюджетов — это и есть прирост датаграммы, и она проверяется на
     * `nginx -t`. Секции нет вовсе, если бюджет нулевой, а нулевой он по
     * умолчанию: заданное превью — это требование извлечь объект.
     */

    /**
     * Пары `[имя, значение]` в порядке получения, а не объект: повторяющееся
     * имя оставлено как есть, потому что правило свёртки — дело читателя.
     * Логгер складывает такие значения через `", "`, как составной заголовок.
     *
     * Третий элемент — признак урезанного значения: `waf_preview` со вторым
     * размером ставит потолок на пару, и значение сверх него режется по границе
     * символа UTF-8. Читатель не должен принимать префикс за оригинал.
     *
     * Секретов здесь нет: `authorization`, `proxy-authorization`, `cookie` и
     * `set-cookie` модуль не пишет, пока их не разрешили явным
     * `waf_preview headers ... deny=none`.
     */
    headers_preview: z.array(PreviewPair).optional(),

    /**
     * Сколько пар секции выброшено целиком: имя заняло больше половины потолка
     * на пару. Обрезать имя нельзя — по обрезку не ищется ни один запрос, — а
     * обрезок значения при таком имени ничего сверх самого имени не расскажет.
     * Поля нет — не выброшено ни одной.
     */
    headers_preview_dropped: z.number().int().positive().optional(),

    /**
     * Строка запроса, разобранная на пары. Значения **не** декодированы:
     * способ кодирования — сама улика, и `?q=%3Cscript%3E` обязано отличаться
     * в записи от `?q=<script>`. Декодирует показ.
     */
    args_preview: z.array(PreviewPair).optional(),

    /** То же, что `headers_preview_dropped`, для строки запроса. */
    args_preview_dropped: z.number().int().positive().optional(),

    /**
     * Префикс тела. UTF-8 проверен: негодная последовательность заменена на
     * U+FFFD, обрыв приходится на границу символа — иначе колонка была бы
     * непригодна для поиска, ради которого и заведена.
     *
     * Есть только если тело к моменту записи прочитано. Заданное на маршруте
     * `waf_preview body` само это и обеспечивает: названный бюджет — требование
     * извлечь. Иначе тело читает волна, которой оно нужно, или архив.
     */
    body_preview: z.string().optional(),

    /** Задержка, добавленная модулем: от `ts` до вынесения итога. */
    waf_latency_us: z.number().int().nonnegative(),
  })
  .strict()
  .refine((m) => m.inspectors[SELF] !== undefined, {
    message: `inspectors.${SELF} есть всегда: это итог модуля`,
    path: ["inspectors", SELF],
  })
  .refine((m) => m.inspectors[m.by]?.verdict === m.verdict, {
    message: "by указывает на участника, чей вердикт стал итогом",
    path: ["by"],
  })
  .refine((m) => (m.verdict === "allow") === (m.code === undefined), {
    message: "code есть тогда и только тогда, когда итог не allow",
    path: ["code"],
  })
  .refine((m) => (m.code === "inspector") === (m.by !== SELF), {
    message: `code inspector — это чужое решение, остальные коды — ${SELF}`,
    path: ["code"],
  })
  .refine((m) => m.code !== "score" || m.score !== undefined, {
    message: "отказ по порогу без score не читается",
    path: ["score"],
  });

export type AgentMessage = z.infer<typeof AgentMessage>;
