import { z } from "zod";

/*
 * Инспектор → JetStream, `PUB waf.audit.inspector.<имя>`. Публикуется **после**
 * ответа в inbox: деталями отчёта дедлайн волны двигать нельзя.
 *
 * Subject приезжает в поле `audit_subject` сообщения модуля, а не зашит в
 * сервисе: куда складывать подробности — часть топологии контура, и менять её
 * должен тот, кто топологию описывает. `audit_subject: null` означает, что
 * деталей с этого инспектора не ждут, и публиковать их не надо.
 *
 * Разделение с `kind=request` жёсткое и намеренное. Про сам запрос — адрес,
 * маршрут, размеры, кто промолчал — знает только модуль, и всё это лежит там.
 * Здесь лежит ровно то, чего у модуля нет и взяться не может: что именно
 * сработало внутри движка. Дублировать контекст запроса сюда нельзя — он
 * разъедется с оригиналом на первой же правке.
 *
 * Склейка — по `ray`. Инвариант: `score` этого события совпадает с
 * `inspectors[<имя>].score` в `kind=request`. Разошлись — значит, событие
 * относится к другой инспекции, и связь по `ray` проверить нечем.
 */

/** Тот же набор, что в ответе инспектора модулю. */
const Verdict = z.enum(["allow", "score", "redirect", "deny"]);

/**
 * Общая шкала. Нужна ровно затем, чтобы находки разных движков сортировались
 * в одном списке: без неё «правило CRS 942100» и «совпадение по списку IP»
 * несравнимы, и логеру нечем выбрать, что показать первым.
 */
const Severity = z.enum(["info", "low", "medium", "high", "critical"]);

/**
 * Где нашли. Единственное место во всём контуре, где место находки внутри
 * запроса вообще названо, — ради подсветки в разборе инцидента.
 *
 * `uri` | `args` | `body` — целиком объект обменника;
 * `header:<имя>` | `cookie:<имя>` — конкретное поле, имя в нижнем регистре;
 * `conn` — свойства соединения, а не содержимое запроса: адрес клиента, TLS.
 * Без него находке IP фильтра некуда деться, а требовать место внутри
 * запроса от того, кто смотрит на соединение, — значит требовать выдумки.
 *
 * Содержимое сюда не копируется: за ним идут в обменник по локатору из
 * `kind=request`. Смещение — от начала названного объекта.
 */
const Target = z
  .string()
  .regex(/^(uri|args|body|conn|header:[!-9;-~]+|cookie:[!-9;-~]+)$/);

/**
 * Одна находка. Форма одна на всех: правило CRS у `modsec`, совпадение списка
 * у `ip`, класс уязвимости у `vlai`, нарушение контракта у `json`. Это и
 * есть унификация — потребитель разбирает находку, не зная, кто её прислал.
 *
 * Всё, что специфично для движка, уезжает в `engine` соседнего уровня.
 */
const Finding = z
  .object({
    /**
     * Что нашли, машинно-читаемо: `sqli`, `xss`, `crs-942100`,
     * `json-schema-mismatch`, `ip-denylist`. Пространство имён открыто, но код
     * обязан быть стабильным между версиями движка — по нему строят исключения.
     */
    code: z.string().min(1),

    severity: Severity,

    target: Target,

    /** Смещение находки внутри объекта из `target`, байты от его начала. */
    offset: z.number().int().nonnegative().optional(),
    length: z.number().int().positive().optional(),

    /**
     * Идентификатор сработавшего правила в терминах движка: `942100`,
     * имя набора, версия модели. Поля нет — находка не правиловая.
     */
    rule: z.string().min(1).optional(),

    /**
     * Уверенность, 0..1. Есть у вероятностных движков и отсутствует у
     * детерминированных: у совпадения по списку уверенности не бывает, и
     * писать туда 1.0 значило бы делать вид, что шкала общая.
     */
    confidence: z.number().min(0).max(1).optional(),

    /**
     * Короткая цитата совпавшего фрагмента, до 256 байт. Именно цитата, а не
     * содержимое: полный объект достаётся из обменника, а сюда попадает столько,
     * сколько нужно, чтобы находку было видно в списке.
     *
     * Инспектор обязан вычистить отсюда всё, что не должно попасть в лог, —
     * запись аудита живёт дольше запроса и читается шире.
     */
    evidence: z.string().max(256).optional(),
  })
  .strict();

export const InspectorAudit = z
  .object({
    v: z.literal(1),
    kind: z.literal("inspector"),

    /** Момент завершения инспекции, UTC с миллисекундами. */
    ts: z.string().datetime({ offset: false }),

    /* --- склейка ---------------------------------------------------------- */

    /**
     * UUID v4 запроса, как приехал в сообщении модуля. Единственный ключ
     * склейки: `rid` для этого не годится — он адресует слот воркера и
     * переиспользуется.
     */
    ray: z
      .string()
      .regex(
        /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/,
      ),
    /** `node` из сообщения модуля, не имя хоста инспектора. */
    node: z.string().min(1),
    phase: z.enum(["request", "response", "frame"]),

    /** Имя, под которым инспектор объявлен в конфигурации модуля. */
    inspector: z.string().min(1),
    /**
     * Профиль маршрута, с которым звали. Без него вердикт не воспроизвести:
     * один инспектор на разных location работает по-разному.
     */
    profile: z.string().min(1),

    /* --- решение ---------------------------------------------------------- */

    /** То же, что уехало модулю в ответе. Расхождение — ошибка инспектора. */
    verdict: Verdict,
    /** Заявка в сумму. Есть ровно при `verdict: "score"`, как и в ответе. */
    score: z.number().int().positive().optional(),

    /**
     * Время внутри движка: без шины, без очереди, без разбора сообщения.
     * Round-trip мерит модуль и пишет в `kind=request`; разница между ними и
     * есть ответ на «инспектор тормозит или тормозит доставка».
     */
    engine_ms: z.number().nonnegative(),

    /* --- находки ---------------------------------------------------------- */

    /**
     * Почему вердикт такой. Пустой массив допустим и осмыслен: инспектор
     * отработал и не нашёл ничего.
     */
    findings: z.array(Finding),

    /**
     * Что инспектор сделал с доставленными ему просьбами соседей. Секции нет,
     * если ему ничего не адресовали.
     *
     * Пишутся **все** доставленные, а не только применённые. «Нет правила» —
     * такая же запись, как остальные: молчание в ответ на просьбу и есть тот
     * случай, который потом разбирают, а «`ip` просил капчу, капчи не было» —
     * самый частый вопрос к этому каналу. Вторая половина ответа — перечень
     * живых действий в `kind=request` у модуля; склейка по `ray`.
     *
     * Отправленные этим инспектором действия сюда не попадают: их называет
     * модуль, и дублировать значило бы иметь два источника одного факта.
     *
     * Словари и правила применения — [inspector-actions.md](../inspector-actions.md).
     */
    actions: z
      .array(
        z
          .object({
            /** Кто попросил. */
            from: z.string().min(1),
            do: z.enum(["challenge", "threshold", "skip", "reauth", "note"]),
            apply: z.enum(["request", "ip", "asn", "session"]),
            code: z
              .string()
              .regex(/^[A-Z][A-Z0-9_]*$/)
              .max(64)
              .optional(),
            /**
             * Что получатель сделал:
             *
             * - `applied` — правило нашлось и просьба учтена целиком: потолков
             *   у правил приёма нет, число держит загрузчик отправителя;
             * - `no_rule` — доставлено, но этого отправителя профиль не слушает.
             */
            outcome: z.enum(["applied", "no_rule"]),
            /**
             * Число, с которым инспектор в итоге работал. Есть у `threshold` и
             * у `note`, и только при `applied`.
             */
            effective: z.number().int().optional(),
          })
          .strict(),
      )
      .optional(),

    /**
     * С каким порогом инспектор в итоге работал, если соседи его двигали
     * (`do: "threshold"`). Без этого поля его собственные вердикты на таком
     * запросе не объяснить: находка «не дотянула до порога», а до какого —
     * неизвестно.
     */
    threshold: z.number().int().optional(),

    /**
     * Своё. Открытый объект: `crs_anomaly_score`, `matched`, версии баз и
     * моделей, счётчики фаз. Незнакомые ключи потребитель пропускает.
     *
     * Открытость здесь — не послабление, а граница: всё, что общо для
     * инспекторов, обязано лежать выше, в фиксированной части. Как только
     * поле из `engine` понадобилось второму движку, ему место в `Finding`.
     *
     * Исключение-соглашение — наблюдение профиля (`mode: observe`): ключи
     * `mode`, `passive: true`, `would_verdict`, `would_code`, `would_score`
     * пишут одинаково все инспекторы с профилями, см.
     * [inspectors.md](../inspectors.md#наблюдение-профиля).
     */
    engine: z.object({}).passthrough().optional(),
  })
  .strict()
  .refine((m) => (m.verdict === "score") === (m.score !== undefined), {
    message: "score — заявка в сумму, она есть ровно при verdict score",
    path: ["score"],
  })
  .refine((m) => m.verdict === "allow" || m.findings.length > 0, {
    message: "вердикт не allow без единой находки нечем объяснить",
    path: ["findings"],
  });

export type InspectorAudit = z.infer<typeof InspectorAudit>;
